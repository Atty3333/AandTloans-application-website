-- AAndTee Loans — Supabase schema (v2). Run in the Supabase SQL editor.
-- Public visitors never touch the database directly: all writes go through the
-- Next.js API route using the service-role key (which bypasses RLS).
-- Only users whose JWT has app_metadata.role = 'admin' can read/update.

-- ---------------------------------------------------------------------------
-- Helper: admin check
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
  SELECT COALESCE(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin';
$$;

-- ---------------------------------------------------------------------------
-- Table
-- ---------------------------------------------------------------------------
CREATE TABLE public.loan_applications (
    id                    UUID PRIMARY KEY,                       -- generated by the API route
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_id               UUID REFERENCES auth.users (id) ON DELETE SET NULL,  -- the applicant's account

    -- Borrower
    full_name             TEXT NOT NULL CHECK (char_length(full_name) BETWEEN 2 AND 120),
    date_of_birth         DATE NOT NULL,
    id_number             TEXT NOT NULL CHECK (id_number ~ '^[0-9]{9}$'),   -- Omang
    phone_number          TEXT NOT NULL CHECK (phone_number ~ '^\+267[0-9]{7,8}$'),
    email                 TEXT NOT NULL,
    address               TEXT NOT NULL,
    institution           TEXT NOT NULL,
    monthly_income        NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (monthly_income >= 0),

    -- Loan
    loan_amount_requested NUMERIC(12, 2) NOT NULL CHECK (loan_amount_requested > 0),
    loan_purpose          TEXT NOT NULL,

    -- Next of kin
    kin_full_name         TEXT NOT NULL,
    kin_relationship      TEXT NOT NULL,
    kin_id_number         TEXT NOT NULL,
    kin_phone             TEXT NOT NULL CHECK (kin_phone ~ '^\+267[0-9]{7,8}$'),
    kin_alt_phone         TEXT CHECK (kin_alt_phone IS NULL OR kin_alt_phone ~ '^\+267[0-9]{7,8}$'),
    kin_address           TEXT NOT NULL,

    -- Optional guarantor (shown on the Loan Application Form)
    guarantor_name        TEXT,
    guarantor_phone       TEXT CHECK (guarantor_phone IS NULL OR guarantor_phone ~ '^\+267[0-9]{7,8}$'),

    -- Supporting documents: [{kind, path, contentType, size}] in the private 'application-documents' bucket
    documents             JSONB NOT NULL DEFAULT '[]'::jsonb,

    -- Consent + audit trail
    consent_given_at      TIMESTAMPTZ NOT NULL,
    terms_version         TEXT NOT NULL,
    submitted_ip          TEXT,
    user_agent            TEXT,

    -- Document (private bucket path, NOT a public URL)
    pdf_path              TEXT NOT NULL,
    pdf_sha256            TEXT NOT NULL CHECK (pdf_sha256 ~ '^[0-9a-f]{64}$'),
    whatsapp_notified_at  TIMESTAMPTZ,

    -- Workflow
    status                TEXT NOT NULL DEFAULT 'PENDING'
                          CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'DISBURSED', 'REPAID')),
    status_updated_at     TIMESTAMPTZ,
    status_updated_by     UUID REFERENCES auth.users (id),

    -- Last admin edit of the applicant's details (full history in application_edits)
    last_edited_at        TIMESTAMPTZ,
    last_edited_by        UUID REFERENCES auth.users (id)
);

-- One PENDING application per Omang and per account. Once the lender has replied
-- (approved / rejected / disbursed / repaid) the applicant may apply again.
CREATE UNIQUE INDEX loan_applications_one_pending_per_id
    ON public.loan_applications (id_number) WHERE status = 'PENDING';
CREATE UNIQUE INDEX loan_applications_one_pending_per_user
    ON public.loan_applications (user_id) WHERE status = 'PENDING' AND user_id IS NOT NULL;

CREATE INDEX loan_applications_created_at_idx ON public.loan_applications (created_at DESC);
CREATE INDEX loan_applications_status_idx     ON public.loan_applications (status);
CREATE INDEX loan_applications_user_id_idx    ON public.loan_applications (user_id);

-- ---------------------------------------------------------------------------
-- Status-change audit columns
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.touch_status_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    NEW.status_updated_at := NOW();
    NEW.status_updated_by := auth.uid();
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER loan_applications_touch_status
BEFORE UPDATE ON public.loan_applications
FOR EACH ROW EXECUTE FUNCTION public.touch_status_change();

-- ---------------------------------------------------------------------------
-- Row Level Security + grants
-- ---------------------------------------------------------------------------
ALTER TABLE public.loan_applications ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.loan_applications FROM anon, authenticated;
GRANT SELECT ON public.loan_applications TO authenticated;
GRANT UPDATE (status) ON public.loan_applications TO authenticated;   -- admins may only change status

CREATE POLICY "Admins can read applications"
ON public.loan_applications FOR SELECT TO authenticated
USING (public.is_admin());

CREATE POLICY "Admins can update application status"
ON public.loan_applications FOR UPDATE TO authenticated
USING (public.is_admin())
WITH CHECK (public.is_admin());

-- No INSERT policy: direct inserts are impossible. The API route uses the service role.

-- Applicants see only a limited, read-only view of their OWN applications.
CREATE OR REPLACE VIEW public.my_loan_applications AS
SELECT id, created_at, loan_amount_requested, loan_purpose, status, status_updated_at
FROM public.loan_applications
WHERE user_id = auth.uid();

REVOKE ALL ON public.my_loan_applications FROM anon, authenticated;
GRANT SELECT ON public.my_loan_applications TO authenticated;

